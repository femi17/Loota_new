const DEEP_AMOUNTS = { w: [180, 240, 300, 360, 420, 480, 600], c: [25, 35, 50, 60, 80, 100, 120], e: [20, 25, 30, 40, 45, 50, 60], b: [1] };
const SOFT_AMOUNTS = { w: [30, 45, 60, 75, 90, 120, 150], c: [5, 8, 10, 12, 15, 20, 25, 30], e: [5, 8, 10, 12, 15, 20] };
const EFFECT = { w: "wait", c: "coins", e: "energy", b: "back" };

export function penalties() {
  const out = [];
  DEEP.forEach(([title, text, scene, fx], i) => {
    const amounts = DEEP_AMOUNTS[fx];
    const amount = amounts[(i * 3) % amounts.length];
    const line = DEEP_COST[fx][i % DEEP_COST[fx].length];
    const n = fx === "w" ? Math.round(amount / 60) : amount;
    out.push({ code: `d-${String(i + 1).padStart(3, "0")}`, tier: "deep", effect: EFFECT[fx], amount, title, body: `${text} ${line(n)}`, scene });
  });
  SOFT.forEach(([title, text, scene], i) => {
    const fx = ["w", "c", "e"][i % 3];
    const amounts = SOFT_AMOUNTS[fx];
    const amount = amounts[(i * 5) % amounts.length];
    const line = SOFT_COST[fx][Math.floor(i / 3) % SOFT_COST[fx].length];
    out.push({ code: `s-${String(i + 1).padStart(3, "0")}`, tier: "soft", effect: EFFECT[fx], amount, title, body: `${text} ${line(amount)}`, scene });
  });
  return out;
}

